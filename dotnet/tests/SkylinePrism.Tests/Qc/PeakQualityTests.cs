    private static void Copy(string path, string select)
    {
        using var conn = new DuckDBConnection("Data Source=:memory:");
        conn.Open();
        using var cmd = conn.CreateCommand();
        cmd.CommandText = $"COPY ({select}) TO '{path.Replace("'", "''")}' (FORMAT PARQUET)";
        cmd.ExecuteNonQuery();
    }

    /// <summary>The golden's transition rows as a parquet file, optionally under Skyline's own names.</summary>
    private static void WriteTransitions(
        string path, JsonElement golden, IReadOnlyDictionary<string, DateTime>? acquiredTimes,
        bool skylineNames = false)
    {
        static string Sql(string s) => "'" + s.Replace("'", "''") + "'";
        static string D(JsonElement e)
        {
            var v = Golden.Num(e);
            return double.IsNaN(v) ? "'NaN'::DOUBLE" : v.ToString("R", CultureInfo.InvariantCulture) + "::DOUBLE";
        }

        var values = new StringBuilder();
        foreach (var row in golden.GetProperty("rows").EnumerateArray())
        {
            var f = row.EnumerateArray().ToArray();
            var sample = f[3].GetString()!;
            if (values.Length > 0)
                values.Append(", ");
            values.Append('(')
                .Append(Sql(f[0].GetString()!)).Append(", ").Append(f[1].GetInt32()).Append(", ")
                .Append(Sql(f[2].GetString()!)).Append(", ").Append(Sql(sample)).Append(", ")
                .Append(D(f[4])).Append(", ").Append(D(f[5])).Append(", ").Append(D(f[6])).Append(", ")
                .Append(D(f[7])).Append(", ")
                .Append(acquiredTimes is not null && acquiredTimes.TryGetValue(sample, out var t)
                    ? $"TIMESTAMP '{t:yyyy-MM-dd HH:mm:ss}'"
                    : "NULL::TIMESTAMP")
                .Append(", 2, 1000.0)");
        }
        var names = skylineNames
            ? new[]
            {
