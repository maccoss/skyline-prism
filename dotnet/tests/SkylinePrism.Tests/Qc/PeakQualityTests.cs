    [Theory]
    [MemberData(nameof(PrecursorCases))]
    public void ScorePrecursor_MatchesGolden(string name)
    {
        var c = Load("precursors.json").GetProperty("cases").EnumerateArray()
            .Single(x => x.GetProperty("name").GetString() == name);
        var s = PeakQuality.ScorePrecursor(
            Golden.Vec(c, "shape"), Golden.Vec(c, "dotp"), Golden.Vec(c, "rt"), Golden.Vec(c, "fwhm"));
        var e = c.GetProperty("expected");

        foreach (var (key, center) in new[]
                 {
                     ("shape", s.Shape), ("dotp", s.DotProduct), ("rt", s.RetentionTime), ("fwhm", s.Fwhm),
                 })
        {
            var ec = e.GetProperty("centers").GetProperty(key);
            Close(Golden.Num(ec, "median"), center.Median, $"{name} {key} median");
            Close(Golden.Num(ec, "scale"), center.Scale, $"{name} {key} scale");
            Assert.Equal(ec.GetProperty("count").GetInt32(), center.Count);
        }

        foreach (var (key, z) in new[]
                 {
                     ("shape", s.ShapeZ), ("dotp", s.DotProductZ), ("rt", s.RetentionTimeZ), ("fwhm", s.FwhmZ),
                 })
        {
            var ez = Golden.Vec(e.GetProperty("z"), key);
            for (var r = 0; r < ez.Length; r++)
                Close(ez[r], z[r], $"{name} z_{key}[{r}]");
        }

        var score = Golden.Vec(e, "score");
        for (var r = 0; r < score.Length; r++)
            Close(score[r], s.Score[r], $"{name} score[{r}]");
    }

    /// <summary>
    /// <c>cohort.json</c> is a working cohort with one degraded run; <c>shifted.json</c> has a run so
    /// far off - 6 min late, peaks 5x as wide - that its summaries lie outside every histogram range,
    /// which must be read back as measured, not as the range's edge.
    /// </summary>
    [Theory]
    [InlineData("cohort.json")]
    [InlineData("shifted.json")]
    public void Cohort_PerRunSummaries_MatchGoldenWithinOneBin(string fixture)
    {
        var g = Load(fixture);
        var runs = g.GetProperty("runs").GetInt32();
        double[][] Rows(string key) => g.GetProperty(key).EnumerateArray().Select(Golden.Vec).ToArray();
        var (shape, dotp, rt, fwhm) = (Rows("shape"), Rows("dotp"), Rows("rt"), Rows("fwhm"));

        var acc = new PeakQuality.Accumulator(runs);
        for (var p = 0; p < shape.Length; p++)
            acc.Add(shape[p], dotp[p], rt[p], fwhm[p]);
        var samples = Enumerable.Range(1, runs).Select(r => $"run{r:00}").ToList();
        var t0 = new DateTime(2026, 1, 1, 8, 0, 0);
        var times = samples.Select((s, i) => (s, t0.AddMinutes(70 * i)))
            .ToDictionary(x => x.s, x => x.Item2, StringComparer.Ordinal);
        var result = acc.Summarize(samples, times, new[] { "all four" });

        var e = g.GetProperty("expected");
        Assert.True(result.OrderedByAcquiredTime);
        Assert.Equal(e.GetProperty("precursors").GetInt32(), result.Precursors);
        Assert.InRange(Math.Abs(Golden.Num(e, "cohort_median") - result.CohortMedian), 0, PeakQuality.Accumulator.ScoreWidth);
        Assert.Equal(
            e.GetProperty("flagged").EnumerateArray().Select(x => x.GetInt32()),
            result.Flagged.Select(r => r.RunOrder));

        var expectedRuns = e.GetProperty("runs").EnumerateArray().ToArray();
        for (var r = 0; r < runs; r++)
        {
            var x = expectedRuns[r];
            var run = result.Runs[r];
            Assert.Equal(samples[r], run.SampleId);
            Assert.Equal(x.GetProperty("scored").GetInt32(), run.ScoredPrecursors);
            void Within(string key, double actual, double width) =>
                Assert.True(Math.Abs(Golden.Num(x, key) - actual) <= width,
                    $"run {r + 1} {key}: expected {Golden.Num(x, key):R}, got {actual:R} (bin {width})");
            Within("score_p10", run.ScoreP10, PeakQuality.Accumulator.ScoreWidth);
            Within("score_median", run.ScoreMedian, PeakQuality.Accumulator.ScoreWidth);
            Within("score_p90", run.ScoreP90, PeakQuality.Accumulator.ScoreWidth);
            Within("shape_correlation", run.ShapeCorrelation, PeakQuality.Accumulator.ShapeWidth);
            Within("isotope_dot_product", run.IsotopeDotProduct, PeakQuality.Accumulator.DotProductWidth);
            Within("rt_deviation", run.RtDeviation, PeakQuality.Accumulator.RtDeviationWidth);
            Within("fwhm_ratio", run.FwhmRatio, PeakQuality.Accumulator.FwhmRatioWidth);
        }
    }

    /// <summary>
    /// The DuckDB projection: each precursor's median per run over its FRAGMENT rows, with MS1 rows,
    /// NaN and a replicate outside the sample list all left out.
    /// </summary>
    [Fact]
    public void StreamPrecursorQuality_TakesFragmentMediansPerRun_MatchingGolden()
    {
        var g = Load("transitions.json");
        var samples = g.GetProperty("samples").EnumerateArray().Select(x => x.GetString()!).ToList();
        var dir = TempDir();
        try
        {
            var path = Path.Combine(dir, "transitions.parquet");
            WriteTransitions(path, g, acquiredTimes: null);
            var cols = new PrecursorQualityColumns(
                "peptide", "charge", "sample", "fragment_ion",
                "shape_correlation", "retention_time", "fwhm", "isotope_dot_product");
            var blocks = MergedParquetReader.StreamPrecursorQuality(MergedDataset.Open(path), cols, samples)
                .ToDictionary(b => (b.Peptide, b.Charge));

            var expected = g.GetProperty("expected").EnumerateArray().ToArray();
            Assert.Equal(expected.Length, blocks.Count);
            foreach (var e in expected)
            {
                var key = (e.GetProperty("peptide").GetString()!, e.GetProperty("charge").GetInt32());
                var b = blocks[key];
                foreach (var (name, actual) in new[]
                         {
                             ("shape", b.ShapeCorrelation), ("rt", b.RetentionTime), ("fwhm", b.Fwhm),
                             ("dotp", b.IsotopeDotProduct),
                         })
                {
                    var want = Golden.Vec(e, name);
                    for (var s = 0; s < samples.Count; s++)
                        Close(want[s], actual[s], $"{key} {name}[{samples[s]}]", 1e-15);
                }
            }
        }
        finally { Directory.Delete(dir, recursive: true); }
    }

    /// <summary>
    /// <see cref="PeakQuality.Measure"/> on an output directory: Skyline's own column names are found,
    /// and the runs come back in ACQUISITION order, not sample-name order.
    /// </summary>
    [Fact]
    public void Measure_ReadsAnOutputDirectory_AndOrdersRunsByAcquiredTime()
    {
        var g = Load("transitions.json");
        var dir = TempDir();
        try
        {
            var bucket = Path.Combine(dir, MergedDataset.DirectoryName, MergedDataset.BucketColumn + "=0");
            Directory.CreateDirectory(bucket);
            // Acquired in reverse name order, so name order and acquisition order disagree. The
            // golden's out-of-list replicate s9 is a run of this directory like any other, last.
            var t0 = new DateTime(2026, 3, 1, 9, 0, 0);
            var times = new Dictionary<string, DateTime>
            {
                ["s5"] = t0, ["s4"] = t0.AddHours(1), ["s3"] = t0.AddHours(2), ["s2"] = t0.AddHours(3),
                ["s1"] = t0.AddHours(4), ["s9"] = t0.AddHours(5),
            };
            WriteTransitions(Path.Combine(bucket, "data_0.parquet"), g, times, skylineNames: true);

            var log = new List<string>();
            var result = PeakQuality.Measure(dir, log: log.Add);

            Assert.NotNull(result);
            Assert.True(result!.OrderedByAcquiredTime);
            Assert.Equal(new[] { "s5", "s4", "s3", "s2", "s1", "s9" }, result.Runs.Select(r => r.SampleId));
            Assert.Equal(new[] { 1, 2, 3, 4, 5, 6 }, result.Runs.Select(r => r.RunOrder));
            Assert.Equal(times["s3"], result.Runs[2].AcquiredTime);
            Assert.Equal(4, result.Precursors);
            Assert.Equal(
                new[] { "shape correlation", "isotope dot product", "retention time", "FWHM" }, result.Metrics);
            Assert.Contains(log, l => l.Contains("scored 4 precursors across 6 runs", StringComparison.Ordinal));

            // The raw per-run median is the median over precursors of the golden's precursor values.
            var shapeByRun = g.GetProperty("expected").EnumerateArray()
                .Select(e => Golden.Vec(e, "shape")).ToArray();
            var samples = g.GetProperty("samples").EnumerateArray().Select(x => x.GetString()!).ToList();
            foreach (var run in result.Runs.Where(r => samples.Contains(r.SampleId)))
            {
                var s = samples.IndexOf(run.SampleId);
                var exact = Stats.NanMedian(shapeByRun.Select(v => v[s]).ToArray());
                Assert.InRange(Math.Abs(exact - run.ShapeCorrelation), 0, PeakQuality.Accumulator.ShapeWidth);
            }
        }
        finally { Directory.Delete(dir, recursive: true); }
    }

