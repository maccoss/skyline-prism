    /// <summary>
    /// The whole path on a real export: the pipeline writes run order from the reports' Acquired Time,
    /// and the QC report built from the same directory has the section, with plots or a render
    /// failure it names.
    /// </summary>
    [Fact]
    public void Pipeline_WritesRunOrder_AndTheReportHasTheSection()
    {
        var mergeDir = Fixtures.Path2("mini", "merge");
        var inputs = new[] { Path.Combine(mergeDir, "mini_plate1.csv"), Path.Combine(mergeDir, "mini_plate2.csv") };
        var config = PrismConfig.Load(Path.Combine(Fixtures.Path2("mini", "e2e-sum"), "config.yaml"));
        config.QcReport.Enabled = true;
        config.QcReport.SavePlots = false;
        var dir = TempDir();
        try
        {
            PrismPipeline.Run(inputs, dir, config);

            var lines = File.ReadAllLines(Path.Combine(dir, "sample_metadata.csv"));
            var header = CsvLine.Split(lines[0]);
            var rows = lines.Skip(1).Where(l => l.Length > 0).Select(CsvLine.Split).ToList();
            var order = rows.Select(f => int.Parse(f[CsvLine.IndexOf(header, "run_order")], CultureInfo.InvariantCulture)).ToList();
            Assert.Equal(Enumerable.Range(1, rows.Count), order.OrderBy(x => x));
            // Run order follows the acquired time it was ranked by.
            var byOrder = rows.OrderBy(f => int.Parse(f[CsvLine.IndexOf(header, "run_order")], CultureInfo.InvariantCulture))
                .Select(f => f[CsvLine.IndexOf(header, "acquired_time")]).ToList();
            Assert.Equal(byOrder.OrderBy(x => x, StringComparer.Ordinal), byOrder);

            var html = File.ReadAllText(Path.Combine(dir, "qc_report.html"));
            Assert.Contains("Peak Quality by Acquisition Order", html);
            Assert.Contains("Peak Quality Score by Run", html);
            Assert.Contains("Peak Quality Metrics by Run", html);

            // And the key turns it off.
            config.QcReport.PeakQuality = false;
            var without = File.ReadAllText(QcReport.Generate(dir, config, savePlots: false));
            Assert.DoesNotContain("Peak Quality by Acquisition Order", without);
        }
        finally { Directory.Delete(dir, recursive: true); }
    }

