                "Product Charge", "Area",
            }
            : new[]
            {
                "peptide", "charge", "fragment_ion", "sample", "shape_correlation", "retention_time", "fwhm",
                "isotope_dot_product", "acquired_time", "product_charge", "area",
            };
        Copy(path, $"SELECT * FROM (VALUES {values}) AS t({string.Join(", ", names.Select(n => $"\"{n}\""))})");
