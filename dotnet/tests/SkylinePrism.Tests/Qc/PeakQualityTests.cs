    /// <summary>Equal to closed-form precision, with NaN required exactly where the golden has NaN.</summary>
    private static void Close(double expected, double actual, string what, double tolerance = 1e-14)
    {
        if (double.IsNaN(expected))
        {
            Assert.True(double.IsNaN(actual), $"{what}: expected NaN, got {actual:R}");
            return;
        }
        Assert.True(Math.Abs(expected - actual) <= tolerance * Math.Max(1, Math.Abs(expected)),
            $"{what}: expected {expected:R}, got {actual:R}");
    }

